const pick = (arr) => arr[Math.floor(Math.random() * arr.length)]

export function botLikesBack(action) {
  if (action === 'super') return true
  return Math.random() < 0.65
}

export function botGreeting(bot) {
  return pick(bot.role === 'f' ? greetingsF : greetingsM)
}

export function botReply(bot) {
  return pick(bot.role === 'f' ? repliesF : repliesM)
}

export const delay = (min, max) => min + Math.floor(Math.random() * (max - min))
